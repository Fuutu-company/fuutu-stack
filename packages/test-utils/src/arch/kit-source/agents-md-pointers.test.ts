import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * Guard test: AGENTS.md is a map — every pointer in the kit block resolves.
 *
 * - every backticked kebab-case name is a skill in `.claude/skills/`
 * - every backticked path (or file name) exists in the repo
 * - every `@fuutu/<pkg>` names a workspace package
 * - every `AGENTS.md §N` cited by skills, agents and hooks is a section
 */

const REPO_ROOT = join(import.meta.dirname, "../../../../../");
const agentsMd = readFileSync(join(REPO_ROOT, "AGENTS.md"), "utf8");
const kitBlock =
	/<!-- BEGIN:fuutu-kit -->([\s\S]*?)<!-- END:fuutu-kit -->/.exec(
		agentsMd,
	)?.[1] ?? "";

const tokens = [...kitBlock.matchAll(/`([^`]+)`/g)].map((m) => m[1] ?? "");
const trackedFiles = spawnSync("git", ["ls-files"], {
	cwd: REPO_ROOT,
	encoding: "utf8",
})
	.stdout.split("\n")
	.filter(Boolean);

const SKILL = /^[a-z]+(-[a-z]+)+$/;
const PATH = /\/|\.(md|mdx|ts|tsx|mjs|json|css|ya?ml)$/;

/** Pointers to untracked locations, with the reason they are not in git. */
const UNTRACKED: Record<string, string> = {
	".source/": "Fumadocs output, generated by `pnpm check-types`",
	"docs/plans/": "local working docs (gitignored `/docs/`)",
};

function resolves(token: string): boolean {
	if (token in UNTRACKED) return true;
	const path = token.replace(/#.*$/, "").replace(/\/$/, "");
	if (existsSync(join(REPO_ROOT, path))) return true;
	// a bare file name or partial path (`proxy-public.ts`, `mcp/server.ts`)
	return trackedFiles.some(
		(f) => f.endsWith(`/${path}`) || f.includes(`/${path}/`),
	);
}

describe("AGENTS.md pointers", () => {
	it("has a kit block", () => {
		expect(kitBlock.length).toBeGreaterThan(1000);
	});

	it("names only skills that exist", () => {
		const skills = tokens.filter((t) => SKILL.test(t));
		expect(skills.length).toBeGreaterThan(10);
		for (const skill of skills) {
			expect(
				existsSync(join(REPO_ROOT, ".claude", "skills", skill, "SKILL.md")),
				`AGENTS.md names \`${skill}\` — no .claude/skills/${skill}/SKILL.md`,
			).toBe(true);
		}
	});

	it("points only at paths that exist", () => {
		const paths = tokens.filter(
			(t) =>
				PATH.test(t) &&
				!/[\s*<]/.test(t) &&
				!t.startsWith("@") &&
				!t.startsWith("/"),
		);
		expect(paths.length).toBeGreaterThan(10);
		const missing = paths.filter((t) => !resolves(t));
		expect(missing, "AGENTS.md points at missing paths").toEqual([]);
	});

	it("names only workspace packages", () => {
		const packages = new Set(readdirSync(join(REPO_ROOT, "packages")));
		for (const t of tokens.filter((t) => t.startsWith("@fuutu/"))) {
			const name = t.split("/")[1]?.replace(/[^a-z-].*$/, "") ?? "";
			if (name === "<domain>" || name === "") continue;
			expect(packages.has(name), `${t} — no packages/${name}`).toBe(true);
		}
	});

	it("keeps every section that skills, agents and hooks cite", () => {
		const sections = new Set(
			[...kitBlock.matchAll(/^## (\d+) · /gm)].map((m) => m[1]),
		);
		expect([...sections]).toEqual(
			Array.from({ length: 11 }, (_, i) => String(i + 1)),
		);
		const citing = trackedFiles.filter(
			(f) =>
				/^\.claude\/(skills|agents|hooks)\//.test(f) && /\.(md|mjs)$/.test(f),
		);
		for (const file of citing) {
			const source = readFileSync(join(REPO_ROOT, file), "utf8");
			for (const m of source.matchAll(/AGENTS\.md`? §(\d+)/g)) {
				expect(sections.has(m[1]), `${file} cites AGENTS.md §${m[1]}`).toBe(
					true,
				);
			}
		}
	});
});
